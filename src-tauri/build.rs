/// 内置主机图标的允许扩展名，须与 service/icons.rs 的 ALLOWED_EXTS 保持一致
const ICON_EXTS: &[&str] = &["svg", "png", "jpg", "jpeg", "gif", "webp"];

/// 扫描 assets/icons-default/ 生成内置图标清单（OUT_DIR/icons_default.rs）。
/// 内置图标 = 往该目录丢文件重新编译即可，无需改 icons.rs 的代码。
///
/// - 生成 `pub static DEFAULT_ICONS: &[(&str, &[u8])]`，路径用
///   concat!(env!("CARGO_MANIFEST_DIR"), ...) 在 crate 编译期解析，与 OUT_DIR 位置无关；
///   用 include_bytes! 而非 include_str!，顺带兼容以后往目录里丢非 svg 的图片
/// - 目录形式 rerun-if-changed 会递归监视增删改；新增文件必须靠它触发
///   （include_bytes! 的隐式依赖只覆盖已嵌入的文件）
/// - 生成内容相同则跳过写入，避免 watcher 无谓重建（同 copy_if_unchanged 思路）
/// - 无条件执行：desktop 与 --no-default-features 的 web server target 都要用
fn gen_default_icons(manifest_dir: &std::path::Path, out_dir: &std::path::Path) {
    let icons_dir = manifest_dir.join("assets/icons-default");
    let entries = std::fs::read_dir(&icons_dir)
        .unwrap_or_else(|e| panic!("读取内置图标目录 {} 失败: {e}", icons_dir.display()));

    let mut names: Vec<String> = Vec::new();
    for entry in entries.flatten() {
        let ok = entry.file_type().map(|t| t.is_file()).unwrap_or(false)
            && entry
                .path()
                .extension()
                .and_then(|s| s.to_str())
                .map(|s| ICON_EXTS.contains(&s.to_ascii_lowercase().as_str()))
                .unwrap_or(false);
        if ok {
            names.push(entry.file_name().to_string_lossy().into_owned());
        }
    }
    names.sort();

    let mut code = String::from(
        "// @generated by build.rs，勿手改：内容来自 assets/icons-default/ 目录扫描\n\
         pub static DEFAULT_ICONS: &[(&'static str, &'static [u8])] = &[\n",
    );
    for name in &names {
        code.push_str(&format!(
            "    ({name:?}, include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/icons-default/{name}\"))),\n"
        ));
    }
    code.push_str("];\n");

    let dst = out_dir.join("icons_default.rs");
    if let Ok(old) = std::fs::read(&dst) {
        if old.as_slice() == code.as_bytes() {
            return;
        }
    }
    std::fs::write(&dst, code).unwrap_or_else(|e| panic!("写入 {} 失败: {e}", dst.display()));
}

fn main() {
    // 内置主机图标清单：编译期扫描 assets/icons-default/ 自动生成（勿手改生成文件）
    {
        let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
        let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
        gen_default_icons(
            std::path::Path::new(&manifest_dir),
            std::path::Path::new(&out_dir),
        );
        println!("cargo:rerun-if-changed=assets/icons-default");
    }

    // Windows 本地终端依赖随包侧载的官方 ConPTY（见 resources/conpty/README.md）。
    // 仅目标平台为 Windows 时复制；并按目标架构选择变体目录
    // （resources/conpty/x86_64 | aarch64，来自官方 NuGet 的 x64 / arm64）。
    //
    // portable-pty 用 LoadLibrary 加载 exe 同目录的 conpty.dll（默认先搜应用目录），
    // conpty.dll 再从自身目录拉起 OpenConsole.exe，因此两个文件必须与 exe 同目录：
    // - 开发/普通构建：直接复制到产物 exe 目录（兼容有无 --target 的 OUT_DIR 布局）
    // - tauri 打包：资源映射无法按架构分支，故先以固定名暂存到
    //   resources/conpty/bin/（已 gitignore），由 tauri.windows.conf.json 映射到安装根目录
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
        let variant = match arch.as_str() {
            "x86_64" => "x86_64",
            "aarch64" => "aarch64",
            other => panic!("resources/conpty 未提供 {other} 架构的 ConPTY 变体（现有 x86_64/aarch64）"),
        };
        let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
        let src_dir = std::path::Path::new(&manifest_dir)
            .join("resources/conpty")
            .join(variant);

        // 1) 复制到产物 exe 目录：OUT_DIR = target[/triple]/<profile>/build/<pkg>-<hash>/out，
        //    向上找到名为 <profile>（PROFILE，debug/release）的目录即 exe 所在目录
        let profile = std::env::var("PROFILE").expect("PROFILE");
        let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
        let exe_dir = std::path::Path::new(&out_dir)
            .ancestors()
            .find(|p| p.file_name().is_some_and(|n| n == profile.as_str()))
            .expect("OUT_DIR 结构异常：未找到 profile 目录")
            .to_path_buf();
        for file in ["conpty.dll", "OpenConsole.exe"] {
            copy_if_unchanged(&src_dir.join(file), &exe_dir.join(file));
            println!("cargo:rerun-if-changed=resources/conpty/{variant}/{file}");
        }

        // 2) 固定名暂存，供 tauri.windows.conf.json 的 resources 映射进安装包。
        //    bin/ 位于 tauri dev 监视的 src-tauri 树内，每轮构建开头就无条件重写
        //    会让 watcher 误判变更并杀掉尚未完成的构建，形成重建死循环，
        //    因此内容相同必须跳过。
        let stage = std::path::Path::new(&manifest_dir).join("resources/conpty/bin");
        std::fs::create_dir_all(&stage).expect("创建暂存目录");
        for file in ["conpty.dll", "OpenConsole.exe"] {
            copy_if_unchanged(&src_dir.join(file), &stage.join(file));
        }
    }

    // tauri-build 负责桌面壳的资源/上下文代码生成；
    // Web server 目标（--no-default-features）不启用 desktop feature，跳过之
    if std::env::var_os("CARGO_FEATURE_DESKTOP").is_some() {
        tauri_build::build();
    }
}

/// 目标缺失或内容不同才复制；内容相同跳过，避免无谓的文件改写
fn copy_if_unchanged(src: &std::path::Path, dst: &std::path::Path) {
    if let (Ok(new), Ok(old)) = (std::fs::read(src), std::fs::read(dst)) {
        if new == old {
            return;
        }
    }
    if let Err(e) = std::fs::copy(src, dst) {
        panic!("复制 {} 到 {} 失败: {e}", src.display(), dst.display());
    }
}
